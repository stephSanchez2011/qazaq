export function t(learn: LearnTrack, key: I18nKey, vars?: Record<string, string | number>): string {
  const ui = uiLang(learn)
  let out: string = S[key][ui]
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      out = out.replaceAll(`{${k}}`, String(v))
    }
  }
  return out
}

